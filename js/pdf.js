    body: r.rows.filter((x) => x.l >= 0.5 || x.age === r.person.age).map((x) => [x.age, x.year, fmt.q(x.q), fmt.q(x.qBase), `${x.mult.toFixed(2)}x`, fmt.int(x.l), fmt.int(x.d), x.e.toFixed(2), fmt.pct(x.S)]),
    theme: 'striped',
    styles: { fontSize: 7.5, halign: 'right', cellPadding: 2.4, textColor: INK },
    headStyles: { fillColor: NAVY, textColor: 255, halign: 'right' },
    alternateRowStyles: { fillColor: [247, 248, 250] },
    columnStyles: { 0: { halign: 'left', fontStyle: 'bold' }, 1: { halign: 'left' } },
