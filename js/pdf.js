      font('normal', 7); color(MUTED); doc.text(t(c.answer).slice(0, 58), M, y + 16);
      const len = (Math.abs(c.vsAverage) / max) * (barW / 2 - 4);
      fill(c.vsAverage >= 0 ? GREEN : RED);
      doc.rect(c.vsAverage >= 0 ? mid : mid - len, y + 3, len, 9, 'F');
      font('bold', 8.5); color(c.vsAverage >= 0 ? GREEN : RED);
      doc.text(`${c.vsAverage >= 0 ? '+' : '-'}${Math.abs(c.vsAverage).toFixed(1)} yr`, W - M, y + 10, { align: 'right' });
